namespace FullstackTemplate.SourceGenerators;

using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

/// <summary>
/// Writes <c>TimeZoneNames</c> of the Server from the files "backward" and "etcetera" of the IANA time zone database.
/// Each line <c>Link TARGET LINK-NAME</c> becomes a link, and each line <c>Zone NAME ...</c> becomes a zone. The Server
/// keeps the files in <c>Domain/TimeZones/tzdata</c>.
/// </summary>
[Generator]
public sealed class TimeZoneNamesGenerator : IIncrementalGenerator
{
	private static readonly string[] FileNames = ["backward", "etcetera"];

	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		var files = context.AdditionalTextsProvider
			.Where(static file => FileNames.Contains(Path.GetFileName(file.Path)))
			.Select(static (file, ct) => (Name: Path.GetFileName(file.Path), Text: file.GetText(ct) ?? SourceText.From(string.Empty)))
			.Collect();

		context.RegisterSourceOutput(files, static (spc, files) =>
		{
			if (files.Length > 0)
				spc.AddSource("TimeZoneNames.g.cs", Source(files.OrderBy(file => file.Name, StringComparer.Ordinal).Select(file => file.Text)));
		});
	}

	private static string Source(IEnumerable<SourceText> texts)
	{
		var links = new StringBuilder();
		var zones = new StringBuilder();
		foreach (var line in texts.SelectMany(text => text.Lines))
		{
			var fields = line.ToString().Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries);
			if (fields.Length >= 3 && fields[0] == "Link")
				links.AppendLine($"        ({Literal(fields[2])}, {Literal(fields[1])}),");
			else if (fields.Length >= 2 && fields[0] == "Zone")
				zones.AppendLine($"        {Literal(fields[1])},");
		}

		return $$"""
			// <auto-generated/>
			namespace FullstackTemplate.Server.Domain.TimeZones;

			internal static class TimeZoneNames
			{
			    /// <summary>Each link name of the IANA files "backward" and "etcetera", with the zone that it names.</summary>
			    public static readonly (string Name, string Target)[] Links =
			    [
			{{links}}    ];

			    /// <summary>Each zone of the IANA files "backward" and "etcetera", such as EST5EDT and Etc/GMT+5.</summary>
			    public static readonly string[] Zones =
			    [
			{{zones}}    ];
			}
			""";
	}

	private static string Literal(string value) =>
		SymbolDisplay.FormatLiteral(value, quote: true);
}
