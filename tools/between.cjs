// node between.cjs <baseURL> <outDir>: the Between date fields with a short start year and a short end year.
const path = require('node:path')
const { chromium } = require('/Users/paul/repos/FullstackTemplate-worktrees/issue-145/frontend/node_modules/@playwright/test')
const [baseURL, outDir] = process.argv.slice(2)
;(async () => {
  const browser = await chromium.launch()
  for (const theme of ['light', 'dark']) {
    const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, locale: 'en-US', timezoneId: 'UTC', reducedMotion: 'reduce', colorScheme: theme })
    await context.addInitScript((t) => localStorage.setItem('ui-theme', t), theme)
    await context.route((url) => url.pathname === '/bff/user', (r) => r.fulfill({ status: 204 }))
    const page = await context.newPage()
    await page.clock.setFixedTime(new Date('2026-08-15T12:00:00Z'))
    await page.goto(baseURL + '/filter-demo')
    await page.getByRole('button', { name: 'Add Filter', exact: true }).click()
    await page.getByRole('menuitem', { name: 'Created Date', exact: true }).click()
    const control = page.getByRole('dialog', { name: 'Created Date filter', exact: true })
    await control.getByRole('button', { name: 'Between', exact: true }).click()
    await control.getByRole('spinbutton', { name: 'month, Start date', exact: true }).click()
    await page.keyboard.type('0310999')
    await page.keyboard.press('Tab')
    await control.getByRole('spinbutton', { name: 'month, End date', exact: true }).click()
    await page.keyboard.type('0320202612')
    await page.keyboard.press('Tab')
    const box = await control.boundingBox()
    await page.screenshot({ path: path.join(outDir, `short-year-between-${theme}.png`), clip: { ...box, height: Math.min(box.height, 260) } })
    await context.close()
  }
  await browser.close()
})()
