namespace FullstackTemplate.SourceGenerators;

using System;
using System.IO;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

/// <summary>
/// Writes <c>TimeZoneLinks</c> of the Server from the file "backward" of the IANA time zone database. Each line
/// <c>Link TARGET LINK-NAME</c> becomes a link. The Server keeps the file in <c>Domain/TimeZones/tzdata</c>.
/// </summary>
[Generator]
public sealed class TimeZoneLinksGenerator : IIncrementalGenerator
{
	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		var sources = context.AdditionalTextsProvider
			.Where(static file => Path.GetFileName(file.Path) == "backward")
			.Select(static (file, ct) => Source(file.GetText(ct) ?? SourceText.From(string.Empty)));

		context.RegisterSourceOutput(sources, static (spc, source) => spc.AddSource("TimeZoneLinks.g.cs", source));
	}

	private static string Source(SourceText text)
	{
		var links = new StringBuilder();
		foreach (var line in text.Lines)
		{
			var fields = line.ToString().Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries);
			if (fields.Length >= 3 && fields[0] == "Link")
				links.AppendLine($"        ({Literal(fields[2])}, {Literal(fields[1])}),");
		}

		return $$"""
			// <auto-generated/>
			namespace FullstackTemplate.Server.Domain.TimeZones;

			internal static class TimeZoneLinks
			{
			    /// <summary>Each link name of the IANA file "backward", with the zone that it names.</summary>
			    public static readonly (string Name, string Target)[] All =
			    [
			{{links}}    ];
			}
			""";
	}

	private static string Literal(string value) =>
		SymbolDisplay.FormatLiteral(value, quote: true);
}
